-- HEIZ DATABASE, schema v2 (complete, for a FRESH database)
-- Existing v1 databases: use sql/003_migration_v2.sql instead.

BEGIN;

-- DATA SOURCES
-- Stores external earthquake information providers.
CREATE TABLE IF NOT EXISTS data_sources (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50) NOT NULL UNIQUE,
    name            VARCHAR(150) NOT NULL,
    base_url        TEXT NOT NULL,
    description     TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- SYNC LOGS
-- Records attempts to retrieve external data.
CREATE TABLE IF NOT EXISTS sync_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id           BIGINT NOT NULL
                        REFERENCES data_sources(id) ON DELETE RESTRICT,

    started_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at         TIMESTAMPTZ,

    status              VARCHAR(20) NOT NULL DEFAULT 'running'
                        CHECK (
                            status IN (
                                'running',
                                'success',
                                'partial',
                                'failed'
                            )
                        ),

    records_received    INTEGER NOT NULL DEFAULT 0
                        CHECK (records_received >= 0),

    records_created     INTEGER NOT NULL DEFAULT 0
                        CHECK (records_created >= 0),

    records_updated     INTEGER NOT NULL DEFAULT 0
                        CHECK (records_updated >= 0),

    records_skipped     INTEGER NOT NULL DEFAULT 0
                        CHECK (records_skipped >= 0),

    error_summary       TEXT,
    request_url         TEXT,

    CHECK (
        finished_at IS NULL
        OR finished_at >= started_at
    )
);

-- EARTHQUAKE EVENTS
-- Main resource for the REST API CRUD operations.
CREATE TABLE IF NOT EXISTS earthquake_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_id           BIGINT NOT NULL
                        REFERENCES data_sources(id) ON DELETE RESTRICT,

    source_event_id     VARCHAR(200),

    last_sync_id        BIGINT
                        REFERENCES sync_logs(id) ON DELETE SET NULL,

    occurred_at         TIMESTAMPTZ,
    source_reported_at  TIMESTAMPTZ,

    location_description TEXT NOT NULL,

    latitude            NUMERIC(9,6),
    longitude           NUMERIC(9,6),

    magnitude           NUMERIC(4,2),
    depth_km            NUMERIC(8,2),

    tsunami_potential   BOOLEAN,          -- true/false only when BMKG's text says so; NULL = no statement
    tsunami_note        TEXT,             -- BMKG "Potensi" text, verbatim
    felt_text           TEXT,             -- BMKG "Dirasakan" text, verbatim
    shakemap_code       VARCHAR(100),     -- BMKG shakemap file name

    source_url          TEXT,
    source_attribution  VARCHAR(200) NOT NULL DEFAULT 'BMKG',

    raw_payload         JSONB,

    imported_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (
        latitude IS NULL
        OR latitude BETWEEN -90 AND 90
    ),

    CHECK (
        longitude IS NULL
        OR longitude BETWEEN -180 AND 180
    ),

    CHECK (
        magnitude IS NULL
        OR magnitude BETWEEN 0 AND 10
    ),

    CHECK (
        depth_km IS NULL
        OR depth_km >= 0
    ),

    UNIQUE (source_id, source_event_id)
);

-- REGIONS
-- Stores normalized geographical region information.
CREATE TABLE IF NOT EXISTS regions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200) NOT NULL,
    region_type     VARCHAR(50) NOT NULL DEFAULT 'area',
    country_code    CHAR(2) NOT NULL DEFAULT 'ID',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (name, region_type, country_code)
);

-- EVENT REGIONS
-- Junction table: many-to-many relationship.
-- One event can mention multiple regions.
-- One region can be associated with multiple events.
CREATE TABLE IF NOT EXISTS event_regions (
    event_id        BIGINT NOT NULL
                    REFERENCES earthquake_events(id) ON DELETE CASCADE,

    region_id       BIGINT NOT NULL
                    REFERENCES regions(id) ON DELETE RESTRICT,

    relationship    VARCHAR(50) NOT NULL DEFAULT 'reported_location',

    PRIMARY KEY (event_id, region_id)
);

-- EVENT UPDATES
-- Keeps a history of meaningful event changes.
CREATE TABLE IF NOT EXISTS event_updates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id        BIGINT NOT NULL
                    REFERENCES earthquake_events(id) ON DELETE CASCADE,

    sync_log_id     BIGINT
                    REFERENCES sync_logs(id) ON DELETE SET NULL,

    change_type     VARCHAR(30) NOT NULL
                    CHECK (
                        change_type IN (
                            'created',
                            'updated',
                            'corrected',
                            'manual_edit'
                        )
                    ),

    changed_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    changed_fields  JSONB NOT NULL DEFAULT '{}'::jsonb,

    note            TEXT
);

-- INDEXES
CREATE INDEX IF NOT EXISTS idx_sync_logs_source_started
    ON sync_logs (source_id, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_earthquake_events_occurred_at
    ON earthquake_events (occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_earthquake_events_location
    ON earthquake_events (latitude, longitude);

CREATE INDEX IF NOT EXISTS idx_earthquake_events_source
    ON earthquake_events (source_id);

CREATE INDEX IF NOT EXISTS idx_event_updates_event_changed
    ON event_updates (event_id, changed_at DESC);

CREATE INDEX IF NOT EXISTS idx_earthquake_events_magnitude
    ON earthquake_events (magnitude DESC) WHERE magnitude IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_earthquake_events_imported_at
    ON earthquake_events (imported_at);

CREATE INDEX IF NOT EXISTS idx_event_updates_changed_at
    ON event_updates (changed_at);

CREATE INDEX IF NOT EXISTS idx_sync_logs_started_at
    ON sync_logs (started_at);
-- No GIN index on raw_payload: the app never queries inside it and GIN indexes are large.

-- INITIAL DATA
-- Register BMKG as the first data source.
INSERT INTO data_sources (
    code,
    name,
    base_url,
    description,
    is_active
)
VALUES (
    'BMKG',
    'Badan Meteorologi, Klimatologi, dan Geofisika',
    'https://data.bmkg.go.id/gempabumi/',
    'Official Indonesian earthquake information source.',
    TRUE
)
ON CONFLICT (code) DO UPDATE SET
    name = EXCLUDED.name,
    base_url = EXCLUDED.base_url,
    description = EXCLUDED.description,
    is_active = EXCLUDED.is_active,
    updated_at = CURRENT_TIMESTAMP;

-- Block Supabase's public Data API (anon key) from these The API connects with a direct
-- database role, which bypasses RLS, so enabling RLS with no policies only closes the side door.
ALTER TABLE data_sources      ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_logs         ENABLE ROW LEVEL SECURITY;
ALTER TABLE earthquake_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE regions           ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_regions     ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_updates     ENABLE ROW LEVEL SECURITY;

COMMIT;
